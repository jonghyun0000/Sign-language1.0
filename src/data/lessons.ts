// 사전(GuidePage)과 무엇이 다른가?
//   사전은 "이미 아는 것을 찾아보는" 격자입니다. 처음 접하는 사람에게는
//   37장의 카드가 한꺼번에 쏟아져서 어디서 시작할지 알 수 없습니다.
//   배우기 모드는 **한 번에 하나씩**, 쉬운 것부터 순서대로 안내합니다.
//
// 커리큘럼 설계 원칙:
//   1. 가장 확실한 것부터 — 1과는 이 앱에서 유일하게 자료로 확인된 ㅎ 입니다.
//   2. 원리를 먼저 — "모음은 방향으로 구분된다"를 알면 4글자를 한 번에 익힙니다.
//   3. 짝으로 묶기 — ㄱ/ㄴ 처럼 같은 수형을 쓰는 글자는 함께 배워야
//      "무엇이 다른지"가 분명해집니다.
//   4. 정직하게 — 근거가 약한 손 모양은 레슨 안에서도 그렇게 밝힙니다.

import type { Confidence } from './handshapes';

/** 레슨 하나. */
export interface Lesson {
  id: string;
  /** 목록에 보일 제목. */
  title: string;
  /** 한 줄 설명. */
  subtitle: string;
  /**
   * 연습 전에 읽는 설명. 손 모양 연습이 없는 '읽기 전용' 레슨은
   * targets 를 비워 둡니다.
   */
  intro?: {
    heading: string;
    /** 문단 목록. */
    body: string[];
  };
  /** 연습할 자모/단어 라벨. GESTURE_RULES 의 label 과 일치해야 합니다. */
  targets: string[];
  /** 연습 중 화면에 계속 보여줄 요령. */
  tip?: string;
  /**
   * 글자 만들기 레슨이면 완성될 글자를 적습니다.
   * 예: targets ['ㄱ','ㅏ'] + goal '가'
   */
  goal?: string;
}

