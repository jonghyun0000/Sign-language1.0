/** 손 모양 연습이 있는 레슨인지. */
export function isPracticeLesson(lesson: Lesson): boolean {
  return lesson.targets.length > 0;
}

/** 전체 연습 대상 개수 (진도율 계산용). */
export function totalPracticeSteps(): number {
  return LESSONS.reduce((sum, l) => sum + l.targets.length, 0);
}

/** 레슨 목록에서 id 로 찾기. */
export function getLesson(id: string): Lesson | undefined {
  return LESSONS.find((l) => l.id === id);
}

/**
 * 레슨 전체의 신뢰도를 한 줄로 요약합니다.
 * 근거가 약한 손 모양이 섞여 있으면 학습자에게 알려야 합니다.
 */
export function lessonConfidenceNote(
  confidences: Confidence[],
): string | null {
  if (confidences.some((c) => c === 'invented')) {
    return '이 레슨에는 근거가 확인되지 않은 임시 손 모양이 있습니다. 실제 지문자와 다를 수 있습니다.';
  }
  if (confidences.every((c) => c === 'verified')) return null;
  return '이 레슨의 손 모양은 아직 추정입니다. 수형 자체는 실재하지만 이 글자에 대응하는지는 확인되지 않았습니다.';
}
